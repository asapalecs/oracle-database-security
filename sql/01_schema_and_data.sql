CREATE TABLE staff (
  id_staff NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  username VARCHAR2(30) NOT NULL UNIQUE,
  nume     VARCHAR2(30) NOT NULL,
  prenume  VARCHAR2(30) NOT NULL,
  functie  VARCHAR2(30) NOT NULL,
  email    VARCHAR2(80),
  CONSTRAINT ck_staff_functie CHECK (functie IN ('ADMIN','ANTRENOR','MEDIC','FINANCIAR'))
);

CREATE TABLE jucator (
  id_jucator NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nume       VARCHAR2(30) NOT NULL,
  prenume    VARCHAR2(30) NOT NULL,
  data_nasterii DATE NOT NULL,
  nationalitate VARCHAR2(30),
  nr_tricou  NUMBER(2),
  act_id_criptat RAW(256),
  telefon_criptat RAW(256),
  observatii_medicale_criptat RAW(512),
  CONSTRAINT uq_jucator_nr_tricou UNIQUE (nr_tricou),
  CONSTRAINT ck_jucator_nr_tricou CHECK (nr_tricou BETWEEN 1 AND 99)
);

CREATE TABLE contract (
  id_contract NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  id_jucator  NUMBER NOT NULL,
  id_staff    NUMBER NOT NULL,
  data_start  DATE NOT NULL,
  data_final  DATE NOT NULL,
  salariu_criptat RAW(256),
  bonus_criptat   RAW(256),
  clauza_reziliere NUMBER(12,2),
  CONSTRAINT fk_contract_jucator FOREIGN KEY (id_jucator) REFERENCES jucator(id_jucator) ON DELETE CASCADE,
  CONSTRAINT fk_contract_staff   FOREIGN KEY (id_staff)   REFERENCES staff(id_staff),
  CONSTRAINT ck_contract_perioada CHECK (data_final > data_start)
);

CREATE TABLE meci (
  id_meci NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  data_meci DATE NOT NULL,
  competitie VARCHAR2(40) NOT NULL,
  adversar   VARCHAR2(40) NOT NULL,
  locatie    VARCHAR2(40) NOT NULL,
  id_staff   NUMBER NOT NULL,
  CONSTRAINT fk_meci_staff FOREIGN KEY (id_staff) REFERENCES staff(id_staff)
);

CREATE TABLE audit_log (
  id_audit NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  event_ts TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  db_user  VARCHAR2(30) NOT NULL,
  actiune  VARCHAR2(10) NOT NULL,
  obiect   VARCHAR2(30) NOT NULL,
  pk_text  VARCHAR2(200),
  detalii  CLOB
);

CREATE INDEX idx_audit_obj_ts ON audit_log(obiect, event_ts);

CREATE OR REPLACE PROCEDURE criptare (
    sir_clar     IN  VARCHAR2,
    sir_criptat  OUT RAW
)
IS
    sir_raw      RAW(2000);
    cheie        VARCHAR2(8) := '12345678';
    cheie_raw    RAW(2000);
    mod_operare  PLS_INTEGER;
BEGIN
    sir_raw   := utl_i18n.string_to_raw(sir_clar, 'AL32UTF8');
    cheie_raw := utl_i18n.string_to_raw(cheie,   'AL32UTF8');

    mod_operare := DBMS_CRYPTO.ENCRYPT_DES
                 + DBMS_CRYPTO.PAD_ZERO
                 + DBMS_CRYPTO.CHAIN_ECB;

    sir_criptat := DBMS_CRYPTO.ENCRYPT(src => sir_raw, typ => mod_operare, key => cheie_raw);
END;
/

CREATE OR REPLACE PROCEDURE decriptare (
    sir_criptat   IN  RAW,
    sir_decriptat OUT VARCHAR2
)
IS
    cheie        VARCHAR2(8) := '12345678';
    cheie_raw    RAW(2000);
    mod_operare  PLS_INTEGER;
    sir_raw      RAW(2000);
BEGIN
    cheie_raw := utl_i18n.string_to_raw(cheie, 'AL32UTF8');

    mod_operare := DBMS_CRYPTO.ENCRYPT_DES
                 + DBMS_CRYPTO.PAD_ZERO
                 + DBMS_CRYPTO.CHAIN_ECB;

    sir_raw := DBMS_CRYPTO.DECRYPT(src => sir_criptat, typ => mod_operare, key => cheie_raw);

    sir_decriptat := RTRIM(utl_raw.cast_to_varchar2(sir_raw), CHR(0));
END;
